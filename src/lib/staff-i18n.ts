/** "2:50 PM" / "下午 2:50" from minutes after midnight (the schedule editor works in local "HH:MM"). */
export function clock(min: number, lang: Lang) {
  const m = ((min % 1440) + 1440) % 1440;
  const h = Math.floor(m / 60);
  const mm = String(m % 60).padStart(2, '0');
  const h12 = ((h + 11) % 12) + 1;
  if (lang === 'en') return `${h12}:${mm} ${h >= 12 ? 'PM' : 'AM'}`;
  const period = h < 12 ? '上午' : h === 12 ? '中午' : h < 18 ? '下午' : '晚上';
  return `${period} ${h12}:${mm}`;
}

