export const dict = (lang: Lang): Dict => (lang === 'zh' ? zh : lang === 'zhs' ? zhs : en);

/** Error text for a code returned by an action (falls back to the code itself). */
export function errorText(lang: Lang, e: { code: string; remaining?: number; left?: number } | string | undefined | null) {
  if (!e) return '';
  const d = dict(lang);
  const code = typeof e === 'string' ? e : e.code;
  if (code === 'not_enough_spots') return d.notEnough(typeof e === 'string' ? 0 : e.remaining ?? 0);
  if (code === 'code_wrong') return d.codeWrong(typeof e === 'string' ? 1 : e.left ?? 1);
  return d.errors[code] ?? code;
}

/** Class for an activity name: bold when it is written in Chinese characters (Young Serif has no bold, so English stays as is). */
export const zhBold = (name: string) => (/\p{Script=Han}/u.test(name) ? ' zhname' : '');
